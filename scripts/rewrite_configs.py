"""Rewrite every stored config.yml into the PEARL format (ADR-010).

Loads each config through the stock yaml.Loader — which still understands the old
`!!python/object:` tags — anchors its locations on the project root, and dumps it back
under short tags and root-relative paths. Supersedes the one-shot KI-001 repair, whose
absolutised text this rewrite consumes as-is. Idempotent.
"""

import argparse
from pathlib import Path

import yaml

from pearl.ai_logger import aiLogger
from pearl.config_yaml import anchor_locations, dataset_owners, dump_config_text
from pearl.run_paths import DATA_ROOT, OUTPUTS_ROOT, REPO_ROOT, RESULTS_ROOT

# The three places a config lands: the run itself, its best/ export (ADR-008), and one
# per swept checkpoint (eval_all_ckpts). The sweep copies are regenerated by the next
# sweep, but they are what `ns-eval --load-config` reads, so they are converted too.
CONFIG_GLOBS = (
    (OUTPUTS_ROOT, "*/*/*/config.yml"),
    (RESULTS_ROOT, "*/*/best/config.yml"),
    (RESULTS_ROOT, "*/*/ckpt_sweep/*/config_eval.yml"),
)

# Runs saved before 2026-07 stored `output_dir: outputs` and `data: data/<scene>`, which
# resolved only through the root symlinks removed that month. The KI-001 repair reached
# the 17 run configs but never the 850 sweep copies, so anchoring alone would give those
# a well-formed path to a directory that does not exist. Both roots moved under assets/
# intact, so restoring one is a matter of naming that parent (ADR-007).
LEGACY_ROOTS = {"outputs": OUTPUTS_ROOT, "data": DATA_ROOT}


def salvage_legacy_root(path: Path) -> Path:
    """Move a pre-2026-07 `<repo>/outputs` or `<repo>/data` location under assets/."""
    if not path.is_relative_to(REPO_ROOT):
        return path
    parts = path.relative_to(REPO_ROOT).parts
    root = LEGACY_ROOTS.get(parts[0]) if parts else None
    return root.joinpath(*parts[1:]) if root else path


ap = argparse.ArgumentParser()
ap.add_argument("--dry-run", action="store_true", help="Report what would change, write nothing.")
args = ap.parse_args()

configs = sorted(path for root, pattern in CONFIG_GLOBS for path in root.glob(pattern))
assert configs, f"No configs found under {OUTPUTS_ROOT} or {RESULTS_ROOT}"

changed = 0
for config_path in configs:
    text = config_path.read_text()
    config = yaml.load(text, Loader=yaml.Loader)
    anchor_locations(config)
    config.output_dir = salvage_legacy_root(config.output_dir)
    for owner in dataset_owners(config):
        if owner.data is not None:
            owner.data = salvage_legacy_root(owner.data)
    rewritten = dump_config_text(config)
    if rewritten == text:
        continue
    changed += 1
    if args.dry_run:
        aiLogger.info(f"would rewrite {config_path}")
    else:
        config_path.write_text(rewritten)
        aiLogger.info(f"rewrote {config_path}")

aiLogger.info(f"{changed}/{len(configs)} configs {'need rewriting' if args.dry_run else 'rewritten'}")
